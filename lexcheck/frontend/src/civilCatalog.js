function normalizeText(value) {
  return (value || '')
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim()
}

function toNumber(value) {
  const parsed = Number(value)
  return Number.isFinite(parsed) ? parsed : 0
}

function sortChildren(children, preferred = []) {
  const preferredIndex = new Map(preferred.map((item, index) => [item, index]))
  return [...children].sort((a, b) => {
    const aIndex = preferredIndex.has(a.category) ? preferredIndex.get(a.category) : Number.MAX_SAFE_INTEGER
    const bIndex = preferredIndex.has(b.category) ? preferredIndex.get(b.category) : Number.MAX_SAFE_INTEGER

    if (aIndex !== bIndex) return aIndex - bIndex
    if (b.laws_count !== a.laws_count) return b.laws_count - a.laws_count
    return a.label.localeCompare(b.label, 'ru')
  })
}

function aggregate(items) {
  return items.reduce(
    (acc, item) => {
      const minYear = toNumber(item.min_year)
      const maxYear = toNumber(item.max_year)
      return {
        laws_count: acc.laws_count + toNumber(item.laws_count),
        articles_count: acc.articles_count + toNumber(item.articles_count),
        min_year: acc.min_year && minYear ? Math.min(acc.min_year, minYear) : (acc.min_year || minYear || null),
        max_year: acc.max_year && maxYear ? Math.max(acc.max_year, maxYear) : (acc.max_year || maxYear || null),
      }
    },
    { laws_count: 0, articles_count: 0, min_year: null, max_year: null },
  )
}

function matchesSection(section, category) {
  const normalized = normalizeText(category)
  return section.matchers.some(matcher => matcher.test(normalized))
}

export function buildCivilCatalog(categoryStats = []) {
  const prepared = categoryStats
    .filter(item => item?.category)
    .map((item, index) => ({
      id: `${index}-${item.category}`,
      category: item.category,
      label: item.category,
      laws_count: toNumber(item.laws_count),
      articles_count: toNumber(item.articles_count),
      min_year: toNumber(item.min_year) || null,
      max_year: toNumber(item.max_year) || null,
    }))

  const assigned = new Set()
  const sections = []

  for (const definition of SECTION_DEFINITIONS) {
    const children = prepared.filter(item => {
      if (assigned.has(item.id)) return false
      return matchesSection(definition, item.category)
    })

    if (!children.length) continue

    children.forEach(item => assigned.add(item.id))
    const sortedChildren = sortChildren(children, definition.preferred)
    const totals = aggregate(sortedChildren)

    sections.push({
      id: definition.id,
      title_ru: definition.title_ru,
      title_uz: definition.title_uz,
      laws_count: totals.laws_count,
      articles_count: totals.articles_count,
      min_year: totals.min_year,
      max_year: totals.max_year,
      children: sortedChildren,
    })
  }

  const unmatched = prepared.filter(item => !assigned.has(item.id))
  if (unmatched.length) {
    const totals = aggregate(unmatched)
    sections.push({
      id: 'misc',
      title_ru: 'Прочие разделы',
      title_uz: 'Boshqa bo‘limlar',
      laws_count: totals.laws_count,
      articles_count: totals.articles_count,
      min_year: totals.min_year,
      max_year: totals.max_year,
      children: sortChildren(unmatched),
    })
  }

  return sections
}

export function findCatalogPath(catalog, category) {
  for (const section of catalog || []) {
    const child = (section.children || []).find(item => item.category === category)
    if (child) {
      return { section, child }
    }
  }
  return { section: null, child: null }
}
